//! The `.pen` document tree, field for field as the schema names it.
//!
//! Every property is optional, as in the file. Values keep their raw form ([`Num`], [`Flag`], strings for
//! closed sets) so a document written back is the document that was read; typed readings live in methods.
//! Keys this version does not know are kept in `extra` and written back after the known ones.

use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};

use crate::value::{Flag, Num};

/// The schema version new documents are written with.
pub const SCHEMA_VERSION: &str = "2.22";

/// A whole `.pen` file.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Document {
    /// Schema version the file was written with.
    pub version: String,
    /// Pencraft's own mark: its format number and the features only it draws ([`crate::stamp`]), kept whole.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub pencraft: Option<Value>,
    /// Top-level nodes, back to front.
    #[serde(default)]
    pub children: Vec<Node>,
    /// Theme axes and their values, e.g. `Mode: [Light, Dark]`; the first value is the default.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub themes: Option<Map<String, Value>>,
    /// Other `.pen` files this one uses, by alias.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub imports: Option<Map<String, Value>>,
    /// Named values that properties bind to with `$name`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub variables: Option<Map<String, Value>>,
    /// Keys this version does not know, kept as they were.
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

impl Default for Document {
    fn default() -> Self {
        Document {
            version: SCHEMA_VERSION.to_owned(),
            pencraft: None,
            children: Vec::new(),
            themes: None,
            imports: None,
            variables: None,
            extra: Map::new(),
        }
    }
}

/// What a node is. Kept as its name, so a type from a newer version survives a round-trip.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(from = "String", into = "String")]
pub enum Kind {
    /// A container with optional flex layout.
    Frame,
    /// A container sized by its children.
    Group,
    /// A rectangle.
    Rectangle,
    /// An ellipse, ring or arc.
    Ellipse,
    /// A regular polygon.
    Polygon,
    /// An SVG path.
    Path,
    /// A straight line (older files).
    Line,
    /// A line between two layers that follows them (see [`crate::connector`]).
    Connector,
    /// A text block.
    Text,
    /// A sticky note.
    Note,
    /// An icon from an icon library.
    Icon,
    /// An icon from an icon font (older files).
    IconFont,
    /// Children generated by a script.
    Script,
    /// A live web page.
    Browser,
    /// An instance of a reusable node.
    Ref,
    /// A type this version does not know.
    Other(String),
}

impl Kind {
    /// The name the file uses.
    #[must_use]
    pub fn name(&self) -> &str {
        match self {
            Kind::Frame => "frame",
            Kind::Group => "group",
            Kind::Rectangle => "rectangle",
            Kind::Ellipse => "ellipse",
            Kind::Polygon => "polygon",
            Kind::Path => "path",
            Kind::Line => "line",
            Kind::Connector => "connector",
            Kind::Text => "text",
            Kind::Note => "note",
            Kind::Icon => "icon",
            Kind::IconFont => "icon_font",
            Kind::Script => "script",
            Kind::Browser => "browser",
            Kind::Ref => "ref",
            Kind::Other(name) => name,
        }
    }

    /// Whether nodes of this kind hold children.
    #[must_use]
    pub fn is_container(&self) -> bool {
        matches!(self, Kind::Frame | Kind::Group)
    }
}

impl From<String> for Kind {
    fn from(name: String) -> Self {
        match name.as_str() {
            "frame" => Kind::Frame,
            "group" => Kind::Group,
            "rectangle" => Kind::Rectangle,
            "ellipse" => Kind::Ellipse,
            "polygon" => Kind::Polygon,
            "path" => Kind::Path,
            "line" => Kind::Line,
            "connector" => Kind::Connector,
            "text" => Kind::Text,
            "note" => Kind::Note,
            "icon" => Kind::Icon,
            "icon_font" => Kind::IconFont,
            "script" => Kind::Script,
            "browser" => Kind::Browser,
            "ref" => Kind::Ref,
            _ => Kind::Other(name),
        }
    }
}

impl From<Kind> for String {
    fn from(kind: Kind) -> Self {
        kind.name().to_owned()
    }
}

/// One fill or stroke paint.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum Paint {
    /// A colour or `$variable` written directly.
    Solid(String),
    /// A paint object (`color`, `gradient`, `image`, `shader`, `mesh_gradient`), kept whole.
    Object(Map<String, Value>),
}

/// `fill` and `stroke`: one paint or a list, painted in order.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum Paints {
    /// A single paint.
    One(Paint),
    /// Several paints, bottom first.
    Many(Vec<Paint>),
}

impl Paints {
    /// The paints in painting order.
    #[must_use]
    pub fn as_slice(&self) -> &[Paint] {
        match self {
            Paints::One(paint) => std::slice::from_ref(paint),
            Paints::Many(paints) => paints,
        }
    }
}

/// `padding`: all sides, `[vertical, horizontal]`, or `[top, right, bottom, left]`.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum Padding {
    /// The same on every side.
    All(Num),
    /// Two or four values.
    Sides(Vec<Num>),
}

/// `cornerRadius`: all corners, or `[top-left, top-right, bottom-right, bottom-left]`.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum Corners {
    /// The same on every corner.
    All(Num),
    /// One value per corner.
    Each(Vec<Num>),
}

/// `strokeWidth`: uniform or per side.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(untagged)]
pub enum StrokeWidth {
    /// The same on every side.
    All(Num),
    /// Per side; a missing side has no stroke.
    Sides(Map<String, Value>),
}

/// A node of any kind; the fields a kind doesn't use stay `None`.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Node {
    /// What the node is.
    #[serde(rename = "type")]
    pub kind: Kind,
    /// Unique id; never contains `/`.
    pub id: String,
    /// Left edge relative to the parent; ignored inside a flex layout.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub x: Option<serde_json::Number>,
    /// Top edge relative to the parent; ignored inside a flex layout.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub y: Option<serde_json::Number>,
    /// Layer name.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
    /// Free text for agents.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub context: Option<String>,
    /// Whether `ref` nodes may instance this node.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reusable: Option<bool>,
    /// Theme axis values for this subtree.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub theme: Option<Map<String, Value>>,
    /// `false` hides the node.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub enabled: Option<Flag>,
    /// Opacity 0–1.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub opacity: Option<Num>,
    /// Mirrored left–right.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub flip_x: Option<Flag>,
    /// Mirrored top–bottom.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub flip_y: Option<Flag>,
    /// `absolute` takes the node out of its parent's flex layout.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub layout_position: Option<String>,
    /// Degrees counter-clockwise around the top-left corner.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub rotation: Option<Num>,
    /// Width: a number, variable, `fit_content` or `fill_container`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub width: Option<Num>,
    /// Height: a number, variable, `fit_content` or `fill_container`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub height: Option<Num>,
    /// Clips children to the frame.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub clip: Option<Flag>,
    /// Flex direction: `none`, `vertical` or `horizontal` (frames default to horizontal).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub layout: Option<String>,
    /// Main-axis gap between children.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub gap: Option<Num>,
    /// Inside padding.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub padding: Option<Padding>,
    /// Main-axis alignment.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub justify_content: Option<String>,
    /// Cross-axis alignment.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub align_items: Option<String>,
    /// Fill paints.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub fill: Option<Paints>,
    /// Stroke paints.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub stroke: Option<Paints>,
    /// Stroke thickness.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub stroke_width: Option<StrokeWidth>,
    /// Stroke alignment: `inner`, `center` or `outer`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub stroke_alignment: Option<String>,
    /// Shadows and blurs, kept whole.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub effect: Option<Value>,
    /// What the node is made of (`frosted`, `liquid_glass`), kept whole.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub material: Option<Value>,
    /// Corner radius.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub corner_radius: Option<Corners>,
    /// Ellipse ring ratio (0 solid, 1 hollow).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub inner_radius: Option<Num>,
    /// Ellipse arc start, degrees counter-clockwise from the right.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub start_angle: Option<Num>,
    /// Ellipse arc length in degrees, positive counter-clockwise.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub sweep_angle: Option<Num>,
    /// Polygon corner count.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub polygon_count: Option<Num>,
    /// `nonzero` or `evenodd`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub fill_rule: Option<String>,
    /// SVG path data.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub geometry: Option<String>,
    /// SVG coordinates `[x, y, w, h]` mapped onto the node box.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub view_box: Option<[f64; 4]>,
    /// Text, note content.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub content: Option<String>,
    /// `auto`, `fixed-width` or `fixed-width-height`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text_growth: Option<String>,
    /// Font family name.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub font_family: Option<String>,
    /// Font size in canvas units.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub font_size: Option<Num>,
    /// Font weight (`"400"`, `"700"`...).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub font_weight: Option<Num>,
    /// Extra space between letters, canvas units.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub letter_spacing: Option<Num>,
    /// `normal` or `italic`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub font_style: Option<String>,
    /// Underlined text.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub underline: Option<Flag>,
    /// Struck-through text.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub strikethrough: Option<Flag>,
    /// Line height as a multiple of the font size.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub line_height: Option<Num>,
    /// `left`, `center`, `right` or `justify`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text_align: Option<String>,
    /// `top`, `middle` or `bottom`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text_align_vertical: Option<String>,
    /// Note colour.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub color: Option<String>,
    /// Icon library.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub library: Option<String>,
    /// Icon name.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub icon: Option<String>,
    /// The node a `ref` instances.
    #[serde(default, rename = "ref", skip_serializing_if = "Option::is_none")]
    pub reference: Option<String>,
    /// Overrides inside a `ref`, by id path.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub descendants: Option<Map<String, Value>>,
    /// Child nodes, back to front.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub children: Option<Vec<Node>>,
    /// Keys this version does not know, kept as they were.
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

impl Node {
    /// A node of `kind` with only an id.
    #[must_use]
    pub fn new(kind: Kind, id: String) -> Node {
        Node {
            kind,
            id,
            x: None,
            y: None,
            name: None,
            context: None,
            reusable: None,
            theme: None,
            enabled: None,
            opacity: None,
            flip_x: None,
            flip_y: None,
            layout_position: None,
            rotation: None,
            width: None,
            height: None,
            clip: None,
            layout: None,
            gap: None,
            padding: None,
            justify_content: None,
            align_items: None,
            fill: None,
            stroke: None,
            stroke_width: None,
            stroke_alignment: None,
            effect: None,
            material: None,
            corner_radius: None,
            inner_radius: None,
            start_angle: None,
            sweep_angle: None,
            polygon_count: None,
            fill_rule: None,
            geometry: None,
            view_box: None,
            content: None,
            text_growth: None,
            font_family: None,
            font_size: None,
            font_weight: None,
            letter_spacing: None,
            font_style: None,
            underline: None,
            strikethrough: None,
            line_height: None,
            text_align: None,
            text_align_vertical: None,
            color: None,
            library: None,
            icon: None,
            reference: None,
            descendants: None,
            children: None,
            extra: Map::new(),
        }
    }

    /// The children, empty for leaves.
    #[must_use]
    pub fn kids(&self) -> &[Node] {
        self.children.as_deref().unwrap_or(&[])
    }

    /// The name shown in the layers list: the layer name, else the text, else the kind.
    #[must_use]
    pub fn display_name(&self) -> String {
        if let Some(name) = self.name.as_deref().filter(|n| !n.is_empty()) {
            return name.to_owned();
        }
        if let Some(text) = self.content.as_deref().filter(|t| !t.is_empty()) {
            return text.lines().next().unwrap_or_default().chars().take(40).collect();
        }
        let kind = self.kind.name();
        let mut chars = kind.chars();
        chars.next().map(|first| first.to_uppercase().chain(chars).collect()).unwrap_or_default()
    }

    /// The flex direction of this node's children.
    #[must_use]
    pub fn layout_mode(&self) -> LayoutMode {
        match self.layout.as_deref() {
            Some("none") => LayoutMode::None,
            Some("vertical") => LayoutMode::Vertical,
            Some("horizontal") => LayoutMode::Horizontal,
            // Human: a frame has a horizontal flex layout when `layout` is missing; groups lay nothing out.
            _ if self.kind == Kind::Frame => LayoutMode::Horizontal,
            _ => LayoutMode::None,
        }
    }

    /// Whether the node opts out of its parent's flex layout.
    #[must_use]
    pub fn is_absolute(&self) -> bool {
        self.layout_position.as_deref() == Some("absolute")
    }
}

/// The flex direction of a container.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LayoutMode {
    /// Children are positioned by their own `x` and `y`.
    None,
    /// Children stack top to bottom.
    Vertical,
    /// Children stack left to right.
    Horizontal,
}

/// Main-axis alignment.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Justify {
    /// Packed at the start.
    Start,
    /// Centred.
    Center,
    /// Packed at the end.
    End,
    /// First and last at the edges, equal gaps between.
    SpaceBetween,
    /// Equal space around each child (half at the edges), as CSS `space-around`.
    SpaceAround,
}

/// Cross-axis alignment.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Align {
    /// At the start.
    Start,
    /// Centred.
    Center,
    /// At the end.
    End,
}

impl Node {
    /// Main-axis alignment, `start` by default.
    #[must_use]
    pub fn justify(&self) -> Justify {
        match self.justify_content.as_deref() {
            Some("center") => Justify::Center,
            Some("end") => Justify::End,
            Some("space_between") => Justify::SpaceBetween,
            Some("space_around") => Justify::SpaceAround,
            _ => Justify::Start,
        }
    }

    /// Cross-axis alignment, `start` by default.
    #[must_use]
    pub fn align(&self) -> Align {
        match self.align_items.as_deref() {
            Some("center") => Align::Center,
            Some("end") => Align::End,
            _ => Align::Start,
        }
    }
}
